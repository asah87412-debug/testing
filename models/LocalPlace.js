const mongoose = require("mongoose");

const localPlaceSchema = new mongoose.Schema({
  name: { type: String, required: true, trim: true },
  module: { type: String, enum: ["activity", "shopping", "petrol", "hospital", "atm"], required: true, index: true },
  category: { type: String, trim: true },
  serviceType: { type: String, trim: true },
  description: String,
  location: { type: String, trim: true },
  address: { type: String, trim: true },
  city: { type: String, trim: true },
  district: { type: String, trim: true },
  province: { type: String, trim: true },
  destination: { type: String, trim: true },
  images: [String],
  image: String,
  imageSource: String,
  imageSourcePage: String,
  imageLicense: String,
  imageCredit: String,
  imageDescription: String,
  imageRelevance: { type: String, enum: ["entity", "category"] },
  catalogKey: { type: String, unique: true, sparse: true },
  dataSource: String,
  dataSourceUrl: String,
  products: [String],
  services: [String],
  nearbyAttractions: [String],
  openingHours: { type: mongoose.Schema.Types.Mixed },
  contact: { phone: String, website: String },
  latitude: { type: Number, min: -90, max: 90 },
  longitude: { type: Number, min: -180, max: 180 },
  price: { type: Number, min: 0 },
  currency: { type: String, default: "NPR" },
  durationMinutes: { type: Number, min: 0 },
  // Per-slot booking capacity (destination-agnostic). slots are start times "HH:MM".
  capacityPerSlot: { type: Number, min: 1, max: 500 },
  slots: [{ type: String, trim: true, maxlength: 10 }],
  meetingPoint: { type: String, trim: true, maxlength: 200 },
  includedServices: [String],
  cancellationPolicy: String,
  difficulty: String,
  indoorOutdoor: { type: String, enum: ["indoor", "outdoor", "both"] },
  participantType: String,
  // Minimum participant age for activities (e.g. 18 for adult-only
  // activities). Absent/zero means no age restriction. Enforced by the
  // booking API, never by display labels alone.
  minAge: { type: Number, min: 0, max: 120 },
  bestSeason: String,
  provider: String,
  requirements: [String],
  safetyInformation: String,
  bookingUrl: String,
  verifiedServices: [String],
  supportedNetworks: [String],
  isDemoData: { type: Boolean, default: true, index: true },
}, { timestamps: true });

module.exports = mongoose.model("LocalPlace", localPlaceSchema);
